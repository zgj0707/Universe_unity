    static string PickPassengerMicroText(Station st, bool isCongested, bool isNight, bool hasScenery, bool hasShop)
    {
        int roll = UnityEngine.Random.Range(0, 100);
        // 55% 概率使用场景精选整句，25% 概率生成带真实站名的生活流句子，20% 概率动态组合多维情绪短句
        if (roll < 55)
        {
            string[] pool = isCongested ? MicroCongestedTexts
                : (st != null && st.portal) ? MicroPortalTexts
                : hasScenery ? MicroSceneryTexts
                : hasShop ? MicroCommercialTexts
                : isNight ? MicroNightTexts
                : MicroSmoothTexts;
            return pool[UnityEngine.Random.Range(0, pool.Length)];
        }
        if (roll < 80 && st != null && !string.IsNullOrEmpty(st.name) && !isCongested)
        {
            string tpl = MicroStationTemplates[UnityEngine.Random.Range(0, MicroStationTemplates.Length)];
            return string.Format(tpl, st.name);
        }
        string role = MicroRoles[UnityEngine.Random.Range(0, MicroRoles.Length)];
        string act = MicroActions[UnityEngine.Random.Range(0, MicroActions.Length)];
        string tail = MicroTailMoods[UnityEngine.Random.Range(0, MicroTailMoods.Length)];
        return role + act + tail;
    }

